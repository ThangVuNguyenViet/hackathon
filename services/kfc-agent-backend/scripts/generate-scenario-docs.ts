function buildCapturePlan(scenarios: LiveScenarioCase[]): ScenarioCapturePlan {
  return {
    version: 4,
    description:
      'Generated GenUI render plan for all canonical outcome scenarios. JSON outcome contracts are authoritative.',
    scenarios: scenarios.map((scenario) => {
      const expectedWidgetsByUserTurn: Record<string, string> = {};
      const acceptableWidgetsByUserTurn: Record<string, string[]> = {};
      const requiredWidgetKinds = new Set<string>();
      for (const turn of scenario.turnExpectations) {
        const genUi = turn.outcome.presentation.genUi;
        if (!genUi.required) {
          if (genUi.allowedWidgetKinds.length > 0) {
            acceptableWidgetsByUserTurn[String(turn.turnIndex)] = [
              'chatTranscript',
              ...genUi.allowedWidgetKinds,
            ];
          }
          continue;
        }
        const [primary, ...alternatives] = genUi.allowedWidgetKinds;
        if (!primary) {
          throw new Error(`${scenario.fileName}#${turn.turnIndex} requires GenUI without an allowed widget`);
        }
        expectedWidgetsByUserTurn[String(turn.turnIndex)] = primary;
        if (alternatives.length > 0) {
          acceptableWidgetsByUserTurn[String(turn.turnIndex)] = [...genUi.allowedWidgetKinds];
        } else {
          requiredWidgetKinds.add(primary);
        }
      }
      return {
        fileName: scenario.fileName,
        requiredWidgetKinds: [...requiredWidgetKinds],
        expectedWidgetsByUserTurn,
        ...(Object.keys(acceptableWidgetsByUserTurn).length > 0
          ? { acceptableWidgetsByUserTurn }
          : {}),
      };
    }),
  };
}
